#!/usr/bin/env python3
"""Run every model measurement, write docs/results/*.json + plots, regenerate docs/results.md, and (optionally)
check the key numbers against measure/baseline/model_baseline.json so CI fails on a regression.

  run_all.py [--check-baseline] [--write-baseline] [--quick]
"""
import argparse, json, shutil, subprocess, sys, time
from pathlib import Path
import numpy as np
import p20

HERE = Path(__file__).resolve().parent
PY = sys.executable

def sh(*args):
    print("+", " ".join(str(a) for a in args), flush=True)
    subprocess.run([PY, *[str(a) for a in args]], check=True, cwd=HERE)

def rate_factor_study(out_dir):
    """Spec 6 / DEVIATIONS: notch error vs engine rate factor (bilinear warp) and coefficient-update block size."""
    import notch_map
    rows = []
    for osf in ("1", "2", "4", "8"):
        r, _ = notch_map.model_sweeps(out_dir, [0.0], 2000.0, 0.0, osf)
        r = r[0]; analog = p20.notch_model(2000.0, 20); analog = analog[analog < 20000]
        errs = [abs(a / b - 1) * 100 for a, b in zip(r["notches_hz"], analog)]
        rows.append(dict(factor=int(osf), notches=len(errs), worst_notch_error_percent=round(max(errs), 3), fc_fit_hz=r["fc_fit_hz"]))
        print(f"engine {osf}x: worst notch error vs analog {max(errs):.3f} % over {len(errs)} notches")
    # coefficient update every 1 vs 8 samples: null test on LFO-modulated noise
    import null_test
    tmp = Path(out_dir) / "tmp"; fs = 48000; rng = np.random.default_rng(2); noise = 0.3 * rng.standard_normal(5 * fs)
    p20.write_wav(tmp / "cb_noise.wav", fs, noise)
    p20.render(tmp / "cb_noise.wav", tmp / "cb1.wav", pitch=440, depth=100, rate=25, resonance=50, output="stereo", sets={"control.coef_block": 1})
    p20.render(tmp / "cb_noise.wav", tmp / "cb8.wav", pitch=440, depth=100, rate=25, resonance=50, output="stereo", sets={"control.coef_block": 8})
    _, a = p20.read_wav(tmp / "cb1.wav"); _, b = p20.read_wav(tmp / "cb8.wav")
    n1, _ = null_test.null(a[0], b[0], fs)
    # 1x vs 4x engine on the same programme (how much the oversampling changes the sound)
    p20.render(tmp / "cb_noise.wav", tmp / "os1.wav", pitch=440, depth=100, rate=2, resonance=0, output="stereo", os="1")
    p20.render(tmp / "cb_noise.wav", tmp / "os4.wav", pitch=440, depth=100, rate=2, resonance=0, output="stereo", os="4")
    _, a = p20.read_wav(tmp / "os1.wav"); _, b = p20.read_wav(tmp / "os4.wav")
    n2, _ = null_test.null(a[0], b[0], fs)
    # block-size independence: 64 vs 4096-sample blocks must null to the noise floor
    p20.render(tmp / "cb_noise.wav", tmp / "b64.wav", pitch=440, depth=100, rate=5, resonance=80, output="stereo", block=64)
    p20.render(tmp / "cb_noise.wav", tmp / "b4096.wav", pitch=440, depth=100, rate=5, resonance=80, output="stereo", block=4096)
    _, a = p20.read_wav(tmp / "b64.wav"); _, b = p20.read_wav(tmp / "b4096.wav")
    n3, _ = null_test.null(a[0], b[0], fs)
    res = dict(rate_factor=rows, coef_block_1_vs_8_residual_db=n1["residual_db_rms"], engine_1x_vs_4x_residual_db=n2["residual_db_rms"], block_64_vs_4096_residual_db=n3["residual_db_rms"])
    print(f"coef block 1 vs 8: {n1['residual_db_rms']} dB; engine 1x vs 4x: {n2['residual_db_rms']} dB; block 64 vs 4096: {n3['residual_db_rms']} dB")
    p20.dump(res, Path(out_dir) / "engine_study.json")
    return res

