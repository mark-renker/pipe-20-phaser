#!/usr/bin/env python3
"""Design the zero-latency IIR oversampling filters and write src/dsp/OversampleFilters.h.

Each stage doubles the rate. The passband is 20 kHz at a 48 kHz host; the stopband edge
is the lowest frequency that would fold back into the passband after decimation.
"""
import numpy as np
from scipy import signal
from pathlib import Path

out = []
def design(name, wp, ws, rp, rs, comment):
    N, Wn = signal.ellipord(wp, ws, rp, rs)
    sos = signal.ellip(N, rp, rs, Wn, output='sos')
    w, h = signal.sosfreqz(sos, worN=16384); f = w / np.pi
    db = 20 * np.log10(np.abs(h) + 1e-30)
    print(f"{name}: order {N}, passband ripple {db[f <= wp].min():.4f} dB, stopband {db[f >= ws].max():.2f} dB")
    out.append(f"// {comment}\n// elliptic order {N}, passband edge {wp:.4f}, stopband edge {ws:.4f} (x engine Nyquist), ripple {rp} dB, attenuation {rs} dB\n")
    out.append(f"static constexpr int {name}_numSections = {sos.shape[0]};\n")
    out.append(f"static constexpr double {name}_sos[{sos.shape[0]}][6] = {{\n")
    for s in sos:
        out.append("    { " + ", ".join(f"{v:.17g}" for v in s) + " },\n")
    out.append("};\n\n")

design("kHalfband2x", 20000/48000, 28000/48000, 0.01, 90, "stage 1 (fs -> 2 fs): passband 20 kHz, stopband 28 kHz at a 48 kHz host")
design("kHalfband4x", 20000/96000, 76000/96000, 0.01, 90, "stage 2 (2 fs -> 4 fs): passband 20 kHz, stopband 76 kHz at a 48 kHz host")
design("kHalfband8x", 20000/192000, 172000/192000, 0.01, 90, "stage 3 (4 fs -> 8 fs): passband 20 kHz, stopband 172 kHz at a 48 kHz host")
hdr = """// Pipe-20 Phaser — zero-latency IIR oversampling filters (generated by measure/design_os_filters.py).
// Second-order sections in scipy 'sos' layout: b0 b1 b2 a0 a1 a2 (a0 == 1).
// All filters are normalised to the engine-rate Nyquist, so a 44.1 kHz host gets a
// proportionally lower passband edge (18.4 kHz) — still above the audio band of interest.
#pragma once
namespace pipe20 {
"""
Path(__file__).resolve().parents[1].joinpath("src/dsp/OversampleFilters.h").write_text(hdr + "".join(out) + "} // namespace pipe20\n")
